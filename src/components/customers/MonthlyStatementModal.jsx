
import { useState, useEffect, useRef, useCallback } from "react";
import {
  Printer,
  X,
  Calendar,
  MessageCircle,
  Wallet,
  TrendingUp,
  TrendingDown,
  RefreshCw,
  FileText,
} from "lucide-react";

import { api } from "../../services/apiClient";
import { useSettings } from "../../contexts/SettingsContext";
import { notify } from "../../utils/notify";
import "../../assets/styles/customers/MonthlyStatementModal.css";

export default function MonthlyStatementModal({ customer, onClose }) {
  const { settings } = useSettings();

  const today = new Date();

  const [month, setMonth] = useState(today.getMonth() + 1);
  const [year, setYear] = useState(today.getFullYear());
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(false);

  const printRef = useRef(null);

  const formatCurrency = (value) =>
    `Rs ${Number(value || 0).toLocaleString("en-PK", {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    })}`;

  const fetchStatement = useCallback(async () => {
    setLoading(true);
    setError(false);

    try {
      const res = await api.get(
        `/api/Customers/statement?customerId=${customer.customerId}&month=${month}&year=${year}`
      );

      setData(res);
    } catch (err) {
      console.error("Statement loading error:", err);
      setError(true);
      setData(null);
    } finally {
      setLoading(false);
    }
  }, [customer.customerId, month, year]);

  useEffect(() => {
    fetchStatement();
  }, [fetchStatement]);

  const transactions = data?.transactions || [];

  const totalAdded = transactions.reduce(
    (sum, tx) => sum + Number(tx.amountAdded || 0),
    0
  );

  const totalPaid = transactions.reduce(
    (sum, tx) => sum + Number(tx.amountPaid || 0),
    0
  );

  const monthName = new Date(year, month - 1).toLocaleString("en", {
    month: "long",
  });

  const handlePrint = () => {
    if (!printRef.current || !data) return;

    const printWindow = window.open("", "_blank", "width=900,height=700");

    if (!printWindow) {
      notify.error("Please allow pop-ups to print the statement.");
      return;
    }

    printWindow.document.write(`
      <!DOCTYPE html>
      <html>
        <head>
          <title>Statement - ${customer.name}</title>
          <style>
            * { box-sizing: border-box; }
            body {
              font-family: Arial, sans-serif;
              color: #222;
              padding: 30px;
              font-size: 13px;
            }
            .statement-print-header {
              text-align: center;
              margin-bottom: 30px;
            }
            .statement-print-header h1 {
              font-size: 25px;
              margin-bottom: 5px;
            }
            .statement-print-header h3 {
              margin-top: 24px;
              letter-spacing: 1px;
            }
            .statement-customer-info {
              display: flex;
              justify-content: space-between;
              margin-bottom: 20px;
              padding: 14px;
              background: #f5f7fa;
            }
            .statement-summary {
              display: flex;
              justify-content: space-between;
              padding: 12px;
              background: #f5f7fa;
              margin-bottom: 20px;
            }
            table {
              width: 100%;
              border-collapse: collapse;
              margin-bottom: 25px;
            }
            th {
              background: #f0f2f5;
              text-align: left;
            }
            th, td {
              border-bottom: 1px solid #ddd;
              padding: 11px 8px;
              font-size: 12px;
            }
            .text-right { text-align: right; }
            .statement-grand-total {
              display: flex;
              justify-content: space-between;
              padding: 15px;
              background: #f0f2f5;
              font-size: 17px;
              font-weight: bold;
            }
            .statement-footer {
              text-align: center;
              margin-top: 35px;
              color: #777;
              font-size: 11px;
            }
            @media print {
              body { padding: 10px; }
              tr { page-break-inside: avoid; }
            }
          </style>
        </head>
        <body>
          ${printRef.current.innerHTML}
          <div class="statement-footer">
            Generated by ${settings.storeName || "SaleKhata"}
          </div>
          <script>
            window.onload = function() {
              window.print();
              window.onafterprint = function() {
                window.close();
              };
            };
          </script>
        </body>
      </html>
    `);

    printWindow.document.close();
  };

  const handleWhatsAppShare = () => {
    if (!data) return;

    let phone = String(customer.phone || "").replace(/\D/g, "");

    if (phone.startsWith("0")) {
      phone = "92" + phone.substring(1);
    } else if (!phone.startsWith("92") && phone.length === 10) {
      phone = "92" + phone;
    }

    if (phone && (phone.length < 11 || phone.length > 15)) {
      notify.error("Customer phone number is invalid.");
      return;
    }

    let text = `*${settings.storeName || "SaleKhata"}*\n`;
    text += `*MONTHLY KHATA STATEMENT*\n\n`;
    text += `Period: ${monthName} ${year}\n`;
    text += `Customer: *${customer.name}*\n`;
    text += `Phone: ${customer.phone || "N/A"}\n`;
    text += `--------------------------\n`;
    text += `Opening Balance: ${formatCurrency(data.openingBalance)}\n`;
    text += `New Udhaar: ${formatCurrency(totalAdded)}\n`;
    text += `Payments Made: ${formatCurrency(totalPaid)}\n`;
    text += `--------------------------\n`;
    text += `*CLOSING BALANCE: ${formatCurrency(data.closingBalance)}*\n\n`;
    text += `Please clear your outstanding balance. Thank you!`;

    const url = phone
      ? `https://wa.me/${phone}?text=${encodeURIComponent(text)}`
      : `https://wa.me/?text=${encodeURIComponent(text)}`;

    window.open(url, "_blank", "noopener,noreferrer");
  };

  return (
    <div
      className="statement-modal-overlay"
      onClick={onClose}
    >
      <div
        className="statement-modal-content"
        onClick={(e) => e.stopPropagation()}
      >
        {/* HEADER */}
        <div className="statement-modal-header">
          <div className="statement-heading">
            <div className="statement-heading-icon">
              <FileText size={20} />
            </div>

            <div>
              <h2>Monthly Statement</h2>
              <p>Customer account summary</p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="statement-close-btn"
            aria-label="Close statement"
          >
            <X size={20} />
          </button>
        </div>

        {/* FILTERS */}
        <div className="statement-filters">
          <div className="statement-filter-label">
            <Calendar size={17} />
            <span>Statement Period</span>
          </div>

          <div className="statement-filter-controls">
            <select
              value={month}
              onChange={(e) => setMonth(Number(e.target.value))}
              aria-label="Select month"
            >
              {Array.from({ length: 12 }, (_, i) => (
                <option key={i + 1} value={i + 1}>
                  {new Date(2000, i).toLocaleString("en", {
                    month: "long",
                  })}
                </option>
              ))}
            </select>

            <select
              value={year}
              onChange={(e) => setYear(Number(e.target.value))}
              aria-label="Select year"
            >
              {Array.from(
                { length: today.getFullYear() - 2024 + 1 },
                (_, i) => 2024 + i
              ).map((y) => (
                <option key={y} value={y}>
                  {y}
                </option>
              ))}
            </select>
          </div>
        </div>

        {/* STATEMENT BODY */}
        <div className="statement-body">

          {loading ? (
            <div className="statement-state">
              <RefreshCw className="statement-spinner" size={28} />
              <h3>Loading statement</h3>
              <p>Please wait while we fetch customer transactions.</p>
            </div>
          ) : error ? (
            <div className="statement-state">
              <FileText size={32} />
              <h3>Unable to load statement</h3>
              <p>Something went wrong while fetching the account details.</p>
              <button
                className="statement-retry-btn"
                onClick={fetchStatement}
              >
                <RefreshCw size={15} />
                Try Again
              </button>
            </div>
          ) : (
            <div className="statement-document" ref={printRef}>

              {/* STORE HEADER */}
              <div className="statement-print-header">
                <h1>{settings.storeName || "SaleKhata"}</h1>
                {settings.storeAddress && <p>{settings.storeAddress}</p>}
                {settings.storePhone && <p>Ph: {settings.storePhone}</p>}

                <div className="statement-document-title">
                  <h3>MONTHLY UDHAAR STATEMENT</h3>
                  <span>{monthName} {year}</span>
                </div>
              </div>

              {/* CUSTOMER DETAILS */}
              <div className="statement-customer-info">
                <div>
                  <span>Customer Name</span>
                  <strong>{customer.name}</strong>
                </div>

                <div>
                  <span>Phone Number</span>
                  <strong>{customer.phone || "N/A"}</strong>
                </div>
              </div>

              {/* SUMMARY */}
              <div className="statement-summary">
                <div className="statement-summary-card">
                  <div className="statement-summary-icon opening-icon">
                    <Wallet size={19} />
                  </div>
                  <div>
                    <span>Opening Balance</span>
                    <strong>{formatCurrency(data?.openingBalance)}</strong>
                  </div>
                </div>

                <div className="statement-summary-card">
                  <div className="statement-summary-icon debit-icon">
                    <TrendingUp size={19} />
                  </div>
                  <div>
                    <span>New Udhaar</span>
                    <strong>{formatCurrency(totalAdded)}</strong>
                  </div>
                </div>

                <div className="statement-summary-card">
                  <div className="statement-summary-icon credit-icon">
                    <TrendingDown size={19} />
                  </div>
                  <div>
                    <span>Payments</span>
                    <strong>{formatCurrency(totalPaid)}</strong>
                  </div>
                </div>
              </div>

              {/* TRANSACTIONS */}
              <div className="statement-transactions-heading">
                <h3>Transaction History</h3>
                <span>{transactions.length} Transactions</span>
              </div>

              <div className="statement-table-wrapper">
                <table className="statement-table">
                  <thead>
                    <tr>
                      <th>Date</th>
                      <th>Items / Reference</th>
                      <th className="text-right">Debit</th>
                      <th className="text-right">Credit</th>
                    </tr>
                  </thead>

                  <tbody>
                    {transactions.length === 0 ? (
                      <tr>
                        <td colSpan="4" className="statement-empty">
                          No transactions found for this month.
                        </td>
                      </tr>
                    ) : (
                      transactions.map((tx, idx) => (
                        <tr key={tx.saleId || tx.paymentId || idx}>
                          <td>
                            {tx.date
                              ? new Date(tx.date).toLocaleDateString("en-PK")
                              : "-"}
                          </td>

                          <td>
                            <div className="statement-reference">
                              {tx.reference || "-"}
                            </div>

                            {tx.items && (
                              <small>{tx.items}</small>
                            )}
                          </td>

                          <td className="text-right debit-amount">
                            {Number(tx.amountAdded || 0) > 0
                              ? formatCurrency(tx.amountAdded)
                              : "-"}
                          </td>

                          <td className="text-right credit-amount">
                            {Number(tx.amountPaid || 0) > 0
                              ? formatCurrency(tx.amountPaid)
                              : "-"}
                          </td>
                        </tr>
                      ))
                    )}
                  </tbody>
                </table>
              </div>

              {/* CLOSING BALANCE */}
              <div className="statement-grand-total">
                <div>
                  <span>Closing Balance</span>
                  <small>Outstanding customer amount</small>
                </div>

                <strong>
                  {formatCurrency(data?.closingBalance)}
                </strong>
              </div>

              <div className="statement-document-footer">
                This is a computer-generated customer account statement.
              </div>

            </div>
          )}
        </div>

        {/* FOOTER ACTIONS */}
        <div className="statement-modal-footer">
          <button
            className="statement-btn statement-btn-close"
            onClick={onClose}
          >
            Close
          </button>

          <button
            className="statement-btn statement-btn-whatsapp"
            onClick={handleWhatsAppShare}
            disabled={loading || error || !data}
          >
            <MessageCircle size={17} />
            WhatsApp
          </button>

          <button
            className="statement-btn statement-btn-print"
            onClick={handlePrint}
            disabled={loading || error || !data}
          >
            <Printer size={17} />
            Print
          </button>
        </div>
      </div>
    </div>
  );
}
